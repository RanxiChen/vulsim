#include "detail.hpp"
#include <chrono>
#include <ctime>
#include <iomanip>
#include <sstream>

namespace simgen {
string genCurrentTimeString() {
    std::chrono::system_clock::time_point now = std::chrono::system_clock::now();
    std::time_t tt = std::chrono::system_clock::to_time_t(now);
    std::tm* ptm = std::localtime(&tt);
    std::ostringstream oss;
    oss << std::put_time(ptm, "%Y-%m-%d %H:%M:%S");
    return oss.str();
}

namespace detail {


vector<string> genHeaderPrelude() {
    static const vector<string> code_header_prelude = {
        "// This header file is generated by VulSim SimGen tool.\n",
        "// Do not modify this file directly.\n",
    };
    vector<string> out = code_header_prelude;
    out.push_back("// Generated on: " + genCurrentTimeString() + "\n");
    out.push_back("\n");
    out.push_back("#pragma once\n");
    out.push_back("\n");
    return out;
}

string childPtrFieldName(const string &name, const vector<ConfigRealValue> &indices) {
    string out = "__instptr_" + name;
    for (auto index : indices) out += "__" + std::to_string(index);
    return out;
}

string childPtrFieldName(const VulStaticModuleInstance &parent, const string &name) {
    for (const auto &child : parent.children)
        if (child->instance_path.back() == name) return childPtrFieldName(name, {});
    throw VulException("Concrete child pointer target not found: " + name);
}

namespace {
vector<ConfigRealValue> childArrayDims(const VulStaticModuleInstance &mod) {
    if (!mod.parent) return {};
    auto it = mod.parent->instances.find(mod.instance_decl_name.empty() ? mod.instance_path.back() : mod.instance_decl_name);
    return it == mod.parent->instances.end() ? vector<ConfigRealValue>{} : it->second.array_dims;
}

} // namespace

bool childIsArrayTemplate(const VulStaticModuleInstance &mod) { return !childArrayDims(mod).empty(); }

const VulStaticModuleInstance &findChildTemplateByName(const VulStaticModuleInstance &mod, const string &name) {
    for (const auto &child : mod.children) if (child->instance_path.back() == name) return *child;
    throw VulException("Concrete child not found: " + name);
}


} // namespace detail

} // namespace simgen
